import React, { useEffect, useRef } from 'react';
import { Stethoscope, Sparkles, Activity } from 'lucide-react';
import { DemoChatMessage } from './DemoChatMessage';
import { isLiveMode } from '../lib/demoApi';
import type { DemoChatMessage as DemoChatMessageType, ScenarioConditionId } from '../types';
import { DEMO_SCENARIOS } from '../lib/scenarios';

interface DemoChatAreaProps {
  messages: DemoChatMessageType[];
  isStreaming: boolean;
  onSelectScenario: (id: ScenarioConditionId) => void;
}

export const DemoChatArea: React.FC<DemoChatAreaProps> = ({
  messages,
  isStreaming,
  onSelectScenario,
}) => {
  const bottomRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages, isStreaming]);

  if (messages.length === 0) {
    return (
      <div className="demo-chat-empty">
        <div className="demo-chat-empty__card">
          <div className="demo-chat-empty__icon-wrapper">
            <Stethoscope size={28} className="text-emerald-500" />
          </div>

          <h2 className="demo-chat-empty__title">MedGemma Pre-Consultation Room</h2>
          <p className="demo-chat-empty__desc">
            Describe your symptoms naturally or run a curated clinical simulation. The intake assistant interviews the patient, conducts NHS safety screening, and compiles a structured briefing for clinician review.
          </p>
          <p className="demo-chat-empty__notice">
            {isLiveMode()
              ? 'Simulation only — not medical advice. Responses are generated by a live AI model via our server. Please don\'t enter real personal information.'
              : 'Simulation only — not medical advice and not connected to a live model. Nothing you type leaves your browser; please don\'t enter real personal information.'}
          </p>

          <div className="demo-chat-empty__scenarios-header">
            <Sparkles size={14} className="text-amber-500" />
            <span>Select a Curated Clinical Case</span>
          </div>

          <div className="demo-chat-empty__scenario-grid">
            {DEMO_SCENARIOS.map((s) => (
              <button
                key={s.id}
                type="button"
                className="demo-chat-empty__scenario-card"
                onClick={() => onSelectScenario(s.id)}
              >
                <div className="demo-chat-empty__scenario-top">
                  <span className="demo-chat-empty__scenario-name">{s.name}</span>
                  <span className="demo-chat-empty__scenario-badge">{s.badgeLabel}</span>
                </div>
                <p className="demo-chat-empty__scenario-pitch">{s.summaryPitch}</p>
              </button>
            ))}
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="demo-chat-area">
      <div className="demo-chat-area__messages">
        {messages.map((message) => (
          <DemoChatMessage key={message.id} message={message} />
        ))}

        {isStreaming && (
          <div className="demo-msg demo-msg--assistant animate-pulse">
            <div className="demo-msg__avatar">
              <Activity size={15} className="demo-msg__avatar-icon--assistant animate-spin" />
            </div>
            <div className="demo-msg__bubble-container">
              <div className="demo-msg__header">
                <span className="demo-msg__sender">MedGemma Clinical AI</span>
                <span className="demo-msg__time">Synthesizing...</span>
              </div>
              <div className="demo-msg__bubble demo-msg__bubble--typing">
                <span className="demo-typing-dot" />
                <span className="demo-typing-dot" />
                <span className="demo-typing-dot" />
              </div>
            </div>
          </div>
        )}

        <div ref={bottomRef} />
      </div>
    </div>
  );
};
